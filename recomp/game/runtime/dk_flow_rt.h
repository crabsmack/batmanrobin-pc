/* dk_flow_rt.h - the native flow runtime's own side (phase 5 ruling R8): what the native bridge
 * (`dkit genesis recomp bridge --mode native`) and the platform under it use. The hand-written
 * C never includes it (it sees dk_flow.h's calls only). Written by the kit's recomp template;
 * implemented in game/runtime/flow.cpp.
 *
 * Hand-written 68000 keeps its control flow on the 68000's stack (yields by restoring a saved
 * A7, returns past the caller, arguments after the jsr, scripts popped as return addresses), so
 * the native build keeps that stack and nothing else of the 68000:
 *   - a register record (d0-d7, a0-a7, SR, USP) the bridge's stubs and slots copy parameters
 *     and results through, as the emulated runners' stubs and slots do through the CPU state;
 *   - A7 and the stack as data at the original addresses (work RAM through the platform's
 *     memory hooks: the comparison reads it, and g_VM2SavedSP-style globals hold A7 values);
 *   - return tokens: a call from C pushes RET_FROM_C + 2 x its depth and waits for it, an RTS
 *     to an outer token unwinds the C in between (dk::Unwind), an RTS to an address nobody waits
 *     for runs on there, as the 68000 continues there;
 *   - a table from original code address to C, generated by the bridge (any other address is
 *     fatal, unless the platform's RAM code hook knows it).
 * Nothing decodes or executes an instruction.
 */
#ifndef DK_FLOW_RT_H
#define DK_FLOW_RT_H

#include <stddef.h>
#include <stdint.h>

#include "dk_flow.h"

/* The bridge's table: every code address the game enters that has C (its slot: the inputs from
   the register record, the C, the outputs back, the RTS), sorted by address. */
extern "C" {
typedef struct DkCodeEntry { uint32_t addr; void (*slot)(void); } DkCodeEntry;
extern const DkCodeEntry dk_code_table[];
extern const int dk_code_count;
}

namespace dk {

struct Unwind {};        /* a call the code never came back from: the C caller unwinds too */

namespace flow {

/* The register record: d[0-7], a[0-7] (a[7] = A7, the stack pointer), the status register
   (system byte with the interrupt mask, condition codes), the user stack pointer. */
struct Regs {
    uint32_t d[8];
    uint32_t a[8];
    uint16_t sr;
    uint16_t pad_;
    uint32_t usp;
};
extern Regs g_regs;

/* Set by dk_flow.h's exits (jump, jump_script, rte): the slot doesn't RTS. */
extern int g_left;

/* A call from C (the bridge's stubs): push a return token, run the code at `code` through the
   table until it returns to the token. A return further out throws Unwind; one nobody waits for
   runs on. */
void call(uint32_t code);
/* The slot's RTS: pop the return address (a token a call waits for, or code to run on at). */
void rts(void);

/* What the platform gives the runtime: work RAM for the stack (big-endian 68000 words and longs
   at their 68000 addresses; ROM reads for the exception vectors), where game functions are
   entered (the platform's sync point), the wait for the V-int (IRQ_WAIT), and RAM code: a
   handler the game runs from work RAM, which the platform carries out in C (nonzero: done). */
struct Host {
    uint16_t (*read16)(uint32_t a);
    uint32_t (*read32)(uint32_t a);
    void     (*write16)(uint32_t a, uint16_t v);
    void     (*write32)(uint32_t a, uint32_t v);
    void     (*entry)(uint32_t addr);
    void     (*irq_wait)(void);
    int      (*ram_code)(uint32_t addr);
};
void install(const Host &h);

/* Reset: run the code at `entry` as the outermost program (it never returns). */
[[noreturn]] void reset(uint32_t entry);

/* An interrupt of `level` at the boundary before `pc`: the exception (SR to supervisor with the
   mask at the level, PC and SR pushed), the vector's handler, its RTE, which must return to `pc`
   (anything else is a task switch: R9, fatal). */
void interrupt(unsigned level, uint32_t pc);

/* The wait for the V-int (dk_mem.h IRQ_WAIT): the platform's. */
void irq_wait(void);

/* A branch plan's snapshot (the runner's --branch-plan) carries the game's stack, with the C
   frames and the run loops on it: the runtime's own state goes with it. */
void branch_save(void);
void branch_restore(void);
/* ... and into a caller's buffer of state_bytes() (the native runner's quick saves and rewind) */
size_t state_bytes(void);
void state_save(void *dst);
void state_load(const void *src);

}  /* namespace flow */
}  /* namespace dk */

#endif /* DK_FLOW_RT_H */
