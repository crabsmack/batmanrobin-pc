std::string value_label(int i, const std::string &v)
{
    const char *key = options_name(i);
    if (const Shown *s = shown(key))
        for (const ValLabel &l : s->vals)
            if (v == l.v) return l.label;
    if (!strcmp(key, "start_stage")) return stage_label(v);
    if (!strcmp(key, "shader_preset")) {   /* a path: its file's name */
        size_t s = v.find_last_of("/\\");
        return s == std::string::npos ? v : v.substr(s + 1);
    }
    if (!strcmp(key, "high_fps")) return v + " Hz";
    if (!strcmp(key, "weapon_level")) return "Level " + v;
    return v;
}

bool differs_from_cart(int i) { return options_get(i) != options_cartridge(i); }

/* ---- state ------------------------------------------------------------------------------------- */

enum Tab { TAB_PLAY, TAB_OPTIONS, TAB_CONTROLS };
enum Press { PRESS_NONE, PRESS_PLAY, PRESS_QUIT };

struct State {
    int tab = TAB_PLAY, want_tab = -1;
    char rom[4096] = "";
    std::string rom_why;        /* "" = the ROM checks out */
    bool show = true;
    std::string focus;          /* the option whose help the panel shows */
    std::string error;          /* why the last press did nothing */
    Press press = PRESS_NONE;
    /* the Controls page */
    int ctl_player = 0, want_player = -1;
    bool cap = false, cap_pad = false;   /* waiting for a key (or a controller input) for a box */
    int cap_player = 0, cap_button = 0, cap_slot = 0;
    Uint32 cap_t0 = 0;
    bool nav_hold = false;      /* a controller input just bound: no controller navigation until all is let go */
    std::string ctl_note;       /* what the last binding did */
};

void check_rom(State &S)
{
    if (!S.rom[0]) { S.rom_why = "Choose your ROM of the game (the USA cartridge): Browse..."; return; }
    std::string why = rom_check_path(S.rom);
    if (why.empty()) S.rom_why.clear();
    else if (why.compare(0, 6, "cannot") == 0) S.rom_why = "That file can't be opened.";
    else S.rom_why = "That file isn't The Adventures of Batman and Robin (USA cartridge). A zipped ROM has to be "
                     "unzipped first; other versions of the cartridge aren't supported.";
}

