float LABEL_W = 300, FIELD_W = 360;   /* scaled in launcher_run */

void focus_help(State &S, const char *key)
{
    if (ImGui::IsItemHovered() || ImGui::IsItemFocused()) S.focus = key;
}

void option_row(State &S, int i)
{
    const char *key = options_name(i);
    const Shown *sh = shown(key);
    std::string cur = options_get(i);
    std::vector<std::string> vals = options_values(i);
    ImGui::PushID(key);
    ImGui::AlignTextToFramePadding();
    ImGui::TextUnformatted(sh ? sh->label : key);
    if (differs_from_cart(i)) { ImGui::SameLine(); ImGui::TextColored(C_TITLE, "*"); }
    ImGui::SameLine(LABEL_W);
    ImGui::SetNextItemWidth(FIELD_W);
    if (sh && sh->checkbox) {
        bool b = cur == "1";
        if (ImGui::Checkbox(b ? "On" : "Off", &b)) options_set(i, b ? "1" : "0");
    } else if (!strcmp(key, "shader_preset")) {   /* a path (R34): the field, Browse... and None */
        static char buf[1024];
        static std::string shown_for = "\x01";
        if (cur != shown_for) { snprintf(buf, sizeof buf, "%s", cur.c_str()); shown_for = cur; }
        float bw = (FIELD_W - px(20)) / 4;
        ImGui::SetNextItemWidth(FIELD_W - 2 * bw - px(20));
        if (ImGui::InputTextWithHint("##v", "None (original)", buf, sizeof buf) && options_set(i, buf)) shown_for = buf;
        focus_help(S, key);
        ImGui::SameLine(0, px(10));
        if (ImGui::Button("Browse...", ImVec2(bw, 0))) {
            char path[1024];
            if (host_pick_shader(path, sizeof path) && options_set(i, path)) { snprintf(buf, sizeof buf, "%s", path); shown_for = path; }
        }
        focus_help(S, key);
        ImGui::SameLine(0, px(10));
        if (ImGui::Button("None", ImVec2(bw, 0)) && options_set(i, "")) { buf[0] = 0; shown_for = ""; }
    } else {
        if (std::find(vals.begin(), vals.end(), cur) == vals.end()) vals.push_back(cur);   /* a value from the file */
        if (ImGui::BeginCombo("##v", value_label(i, cur).c_str())) {
            for (const std::string &v : vals) {
                bool sel = v == cur;
                if (ImGui::Selectable(value_label(i, v).c_str(), sel)) options_set(i, v);
                if (sel) ImGui::SetItemDefaultFocus();
            }
            ImGui::EndCombo();
        }
    }
    focus_help(S, key);
    ImGui::PopID();
}

/* the options in the launcher's order (shown_table's), then any it has no entry for */
std::vector<int> display_order()
{
    std::vector<int> o;
    for (const Shown &s : shown_table())
        for (int i = 0; i < options_count(); i++)
            if (!strcmp(options_name(i), s.key)) o.push_back(i);
    for (int i = 0; i < options_count(); i++)
        if (!shown(options_name(i))) o.push_back(i);
    return o;
}

const char *group_of(int i)
{
    const Shown *s = shown(options_name(i));
    return s ? s->group : "Other";
}

void options_page(State &S, float h)
{
    ImGui::BeginChild("opts", ImVec2(0, h - px(96)));
    for (const char *g : k_groups) {
        bool any = false;
        for (int i = 0; i < options_count(); i++) any |= !strcmp(group_of(i), g);
        if (!any) continue;
        ImGui::Spacing();
        ImGui::PushStyleColor(ImGuiCol_Text, C_ACCENT);
        ImGui::SeparatorText(g);
        ImGui::PopStyleColor();
        ImGui::TextColored(C_DIM, "%s", !strcmp(g, "Picture") ? "How it looks (16:9 wide gameplay also changes the game).   * = changed from the cartridge."
                                      : !strcmp(g, "Sound")   ? "Only how it sounds, never the game.   * = changed from the cartridge."
                                                              : "These change the game.   * = changed from the cartridge.");
        for (int i : display_order())
            if (!strcmp(group_of(i), g)) option_row(S, i);
    }
    ImGui::EndChild();
    ImGui::BeginChild("help", ImVec2(0, px(84)), ImGuiChildFlags_Borders, ImGuiWindowFlags_NoScrollbar);
    int f = -1;
    for (int i = 0; i < options_count(); i++)
        if (S.focus == options_name(i)) f = i;
    if (f >= 0) {
        const Shown *sh = shown(options_name(f));
        ImGui::TextColored(C_ACCENT, "%s", sh ? sh->label : options_name(f));
        ImGui::PushTextWrapPos(0);
        ImGui::TextUnformatted(sh ? sh->help : options_what(f));
        ImGui::PopTextWrapPos();
    } else {
        ImGui::TextColored(C_DIM, "Point at an option (or move to it with the arrow keys or a controller) to see what it does.");
    }
    ImGui::EndChild();
}

void play_page(State &S)
{
    ImGui::SeparatorText("Your game");
    ImGui::SetNextItemWidth(-px(150));
    if (ImGui::InputText("##rom", S.rom, sizeof S.rom)) check_rom(S);
    ImGui::SameLine();
    if (ImGui::Button("Browse...", ImVec2(-1, 0))) {
        char path[4096];
        if (host_pick_rom(path, sizeof path)) { snprintf(S.rom, sizeof S.rom, "%s", path); check_rom(S); }
    }
    if (S.rom_why.empty()) ImGui::TextColored(C_OK, "Verified: The Adventures of Batman and Robin, USA cartridge");
    else {
        ImGui::PushStyleColor(ImGuiCol_Text, C_BAD);
        ImGui::PushTextWrapPos(0);
        ImGui::TextUnformatted(S.rom_why.c_str());
        ImGui::PopTextWrapPos();
        ImGui::PopStyleColor();
    }
    ImGui::Spacing();
    ImGui::SeparatorText("Changed from the cartridge");
    int n = 0;
    for (int i : display_order()) {
        std::string cur = options_get(i);
        if (!differs_from_cart(i)) continue;
        const Shown *sh = shown(options_name(i));
        ImGui::BulletText("%s: %s", sh ? sh->label : options_name(i),
                          sh && sh->checkbox ? (cur == "1" ? "on" : "off") : value_label(i, cur).c_str());
        n++;
    }
    if (!n) ImGui::TextColored(C_DIM, "Nothing: it looks, sounds and plays exactly like the cartridge.");
    if (ImGui::Button("Change options...")) S.want_tab = TAB_OPTIONS;
    ImGui::SameLine();
    if (ImGui::Button("Reset to the defaults"))
        for (int i = 0; i < options_count(); i++) options_set(i, options_values(i)[0]);
    if (ImGui::IsItemHovered()) ImGui::SetTooltip("The game as the cartridge plays it, with the music on chips of its own and the picture filling the window (Even pixels).");
    ImGui::SameLine();
    if (ImGui::Button("Everything as the cartridge"))
        for (int i = 0; i < options_count(); i++) options_set(i, options_cartridge(i));
    if (ImGui::IsItemHovered()) ImGui::SetTooltip("The cartridge's sound too: one set of sound chips, and the picture at a whole multiple (Whole number).");
    ImGui::Spacing();
    ImGui::SeparatorText("Controls");
    if (ImGui::BeginTable("ctl", 3, ImGuiTableFlags_SizingStretchProp)) {
        /* player 1's, as set on the Controls page */
        static const int move[] = {CB_UP, CB_DOWN, CB_LEFT, CB_RIGHT}, abc[] = {CB_A, CB_B, CB_C}, st[] = {CB_START};
        struct Row { const char *name; const int *b; int n; } rows[] = {{"Move", move, 4}, {"A  B  C", abc, 3}, {"Start", st, 1}};
        std::string pad_head = "Controller (player 1: " + controls_device_label(0) + ")";
        if (g_controls[0].device == "none") pad_head = "Controller (player 1: none)";
        ImGui::TableNextRow();
        ImGui::TableSetColumnIndex(1);
        ImGui::TextColored(C_DIM, "Keyboard (player 1)");
        ImGui::TableSetColumnIndex(2);
        ImGui::TextColored(C_DIM, "%s", pad_head.c_str());
        for (const Row &r : rows) {
            ImGui::TableNextRow();
            ImGui::TableSetColumnIndex(0);
            ImGui::TextColored(C_DIM, "%s", r.name);
            ImGui::TableSetColumnIndex(1);
            ImGui::TextUnformatted(controls_summary(0, r.b, r.n, true).c_str());
            ImGui::TableSetColumnIndex(2);
            ImGui::TextUnformatted(controls_summary(0, r.b, r.n, false).c_str());
        }
        ImGui::TableNextRow();
        ImGui::TableSetColumnIndex(0);
        ImGui::TextColored(C_DIM, "While playing");
        ImGui::TableSetColumnIndex(1);
        ImGui::TextUnformatted("F4 scaling, F8 shader, F9 frame rate, F10 16:9, F11 fullscreen, Esc quit");
        /* quick saves and rewind (rewind.cpp, R33): Rewind's inputs are player 1's (Controls page) */
        static const int rw[] = {CB_REWIND};
        std::string rk = controls_summary(0, rw, 1, true), rp = controls_summary(0, rw, 1, false), how;
        if (rk != "-") how = rk;
        if (rp != "-" && g_controls[0].device != "none") how += (how.empty() ? "" : " or ") + rp;
        std::string line = "F5 quick save, F7 load, F6 slot" + (how.empty() ? std::string() : "; hold " + how + " to rewind");
        ImGui::TableNextRow();
        ImGui::TableSetColumnIndex(1);
        ImGui::TextUnformatted(line.c_str());
        if (ImGui::IsItemHovered())
            ImGui::SetTooltip("Four quick save slots (F6 picks the next), kept while the game runs: they are gone\n"
                              "when it quits. Rewind goes back up to a minute, its sound played backwards.");
        ImGui::EndTable();
    }
    if (ImGui::Button("Change controls...")) S.want_tab = TAB_CONTROLS;
}

/* ---- the Controls page -------------------------------------------------------------------------- */

void capture_start(State &S, int p, int b, int slot, bool pad)
{
    S.cap = true;
    S.cap_player = p;
    S.cap_button = b;
    S.cap_slot = slot;
    S.cap_pad = pad;
    S.cap_t0 = SDL_GetTicks();
    S.ctl_note.clear();
    controls_capture_begin();
}

void cell_clear(int p, int b, int slot, bool pad)
{
    if (pad) g_controls[p].pad[b][slot] = PadIn();
    else g_controls[p].key[b][slot] = 0;
}

/* An event while a box waits for its input: true when the box took it (ImGui doesn't see it). Key-ups
   always go on to ImGui, so a key that started the wait isn't left held there. */
bool capture_event(State &S, const SDL_Event &e)
{
    if (!S.cap) return false;
    int p = S.cap_player, b = S.cap_button, s = S.cap_slot;
    if (e.type == SDL_KEYDOWN) {
        if (e.key.repeat) return true;
        int sc = e.key.keysym.scancode;
        if (sc == SDL_SCANCODE_ESCAPE) S.ctl_note = "Cancelled: the box is as it was.";
        else if (sc == SDL_SCANCODE_BACKSPACE || sc == SDL_SCANCODE_DELETE) { cell_clear(p, b, s, S.cap_pad); S.ctl_note = "Cleared."; }
        else if (S.cap_pad) { S.ctl_note = "That's a key: this box takes a controller's button or stick (Esc cancels)."; return true; }
        else S.ctl_note = controls_bind_key(p, b, s, sc);
        S.cap = false;
        return true;
    }
    if (e.type == SDL_TEXTINPUT) return true;
    PadIn in;
    if (controls_capture_pad(e, &in)) {
        S.nav_hold = true;
        if (!S.cap_pad) { S.ctl_note = "That's a controller: this box takes a key. Use a Controller box (Esc cancels)."; return true; }
        S.ctl_note = controls_bind_pad(p, b, s, in);
        S.cap = false;
        return true;
    }
    if (e.type == SDL_CONTROLLERBUTTONDOWN || e.type == SDL_CONTROLLERAXISMOTION) return true;
    if (e.type == SDL_MOUSEBUTTONDOWN) { S.cap = false; S.ctl_note.clear(); }   /* a click elsewhere: given up (the click goes on) */
    return false;
}

void bind_cell(State &S, int p, int b, int slot, bool pad, float w)
{
    ImGui::PushID(slot + (pad ? 2 : 0));
    bool waiting = S.cap && S.cap_player == p && S.cap_button == b && S.cap_slot == slot && S.cap_pad == pad;
    std::string label = pad ? controls_pad_label(g_controls[p].pad[b][slot], p) : controls_key_label(g_controls[p].key[b][slot]);
    bool empty = label.empty();
    if (waiting) label = (SDL_GetTicks() / 400) % 2 ? (pad ? "press a button..." : "press a key...") : "";
    int colors = 0;
    if (waiting) {
        ImGui::PushStyleColor(ImGuiCol_Button, C_ACCENT);
        ImGui::PushStyleColor(ImGuiCol_ButtonHovered, C_ACCENT);
        ImGui::PushStyleColor(ImGuiCol_Text, C_ON_ACCENT);
        colors = 3;
    } else if (empty) {
        ImGui::PushStyleColor(ImGuiCol_Button, hex(K_FIELD));
        ImGui::PushStyleColor(ImGuiCol_Text, C_DIM);
        colors = 2;
    }
    if (ImGui::Button((label + "##c").c_str(), ImVec2(w, 0)) && !waiting) capture_start(S, p, b, slot, pad);
    ImGui::PopStyleColor(colors);
    if (!S.cap) {
        bool clear = ImGui::IsItemClicked(ImGuiMouseButton_Right);
        if (ImGui::IsItemFocused())
            clear |= ImGui::IsKeyPressed(ImGuiKey_Delete) || ImGui::IsKeyPressed(ImGuiKey_Backspace) ||
                     ImGui::IsKeyPressed(ImGuiKey_GamepadFaceLeft, false);
        if (clear && !empty) { cell_clear(p, b, slot, pad); S.ctl_note = "Cleared."; }
    }
    if (ImGui::IsItemHovered() && !S.cap)
        ImGui::SetTooltip(pad ? "Click, then press a button or move a stick on a controller.\nRight-click or Delete clears it."
                              : "Click, then press a key.\nRight-click or Delete clears it.");
    ImGui::PopID();
}

/* the lights: a filled circle when the game would see the button pressed */
void light(bool on)
{
    ImVec2 c = ImGui::GetCursorScreenPos();
    float r = px(6), h = ImGui::GetFrameHeight();
    ImDrawList *dl = ImGui::GetWindowDrawList();
    ImVec2 ctr(c.x + r + px(2), c.y + h / 2);
    if (on) dl->AddCircleFilled(ctr, r, ImGui::GetColorU32(C_OK));
    else dl->AddCircle(ctr, r, ImGui::GetColorU32(hex(K_BORDER)), 0, px(1.5f));
    ImGui::Dummy(ImVec2(r * 2 + px(4), h));
}

const char *layout_name(int l)
{
    return l == KEYS_ARROWS ? "Arrow keys, Z X C, Enter" : l == KEYS_WASD ? "W A S D, J K L, Space" : l == KEYS_NONE ? "No keys" : "Your own keys";
}

void controller_combo(State &S, int p)
{
    (void)S;
    PlayerControls &c = g_controls[p];
    std::vector<CtlDevice> devs = controls_devices();
    std::string cur = c.device == "auto" ? "Any controller (in the order plugged in)"
                    : c.device == "none" ? "None (keyboard only)"
                                         : (c.device_name.empty() ? std::string("A controller") : c.device_name);
    bool here = c.device == "auto" || c.device == "none";
    for (const CtlDevice &d : devs) here |= d.guid == c.device;
    if (!here) cur += " (not plugged in)";
    ImGui::SetNextItemWidth(FIELD_W);
    if (ImGui::BeginCombo("##dev", cur.c_str())) {
        bool changed = false;
        if (ImGui::Selectable("Any controller (in the order plugged in)", c.device == "auto")) { c.device = "auto"; changed = true; }
        std::vector<std::string> shown_guids;
        for (const CtlDevice &d : devs) {
            if (std::find(shown_guids.begin(), shown_guids.end(), d.guid) != shown_guids.end()) continue;
            shown_guids.push_back(d.guid);
            int n = 0;
            for (const CtlDevice &o : devs) n += o.guid == d.guid;
            std::string l = d.name + (n > 1 ? " (" + std::to_string(n) + " plugged in)" : "") + (d.generic ? "  [generic]" : "");
            ImGui::PushID(d.guid.c_str());
            if (ImGui::Selectable(l.c_str(), c.device == d.guid)) { c.device = d.guid; c.device_name = d.name; changed = true; }
            ImGui::PopID();
        }
        if (!here && ImGui::Selectable(cur.c_str(), true)) {}
        if (ImGui::Selectable("None (keyboard only)", c.device == "none")) { c.device = "none"; changed = true; }
        ImGui::EndCombo();
        if (changed) controls_reassign();
    }
    if (ImGui::IsItemHovered())
        ImGui::SetTooltip("Any: controllers go to players 1 and 2 in the order they are plugged in.\n"
                          "A named one: this player always gets that controller (another of the\n"
                          "same model goes to the other player if they asked for it).");
}

