void save_shot(SDL_Renderer *r, const char *path)
{
    int w, h;
    SDL_GetRendererOutputSize(r, &w, &h);
    SDL_Surface *s = SDL_CreateRGBSurfaceWithFormat(0, w, h, 32, SDL_PIXELFORMAT_ARGB8888);
    if (!s) return;
    if (SDL_RenderReadPixels(r, nullptr, SDL_PIXELFORMAT_ARGB8888, s->pixels, s->pitch) == 0) SDL_SaveBMP(s, path);
    SDL_FreeSurface(s);
}

/* one command of the test script; a `shot` is taken after the frame is drawn */
void test_command(State &S, const std::string &line, std::string *shot)
{
    size_t sp = line.find(' ');
    std::string cmd = line.substr(0, sp), arg = sp == std::string::npos ? "" : line.substr(sp + 1);
    std::string a1 = arg.substr(0, arg.find(' ')), a2 = arg.find(' ') == std::string::npos ? "" : arg.substr(arg.find(' ') + 1);
    if (cmd == "tab") S.want_tab = a1 == "options" ? TAB_OPTIONS : a1 == "controls" ? TAB_CONTROLS : TAB_PLAY;
    else if (cmd == "player") S.want_player = atoi(a1.c_str()) - 1;
    else if (cmd == "bind" || cmd == "capture" || cmd == "keys" || cmd == "controller" || cmd == "deadzone" || cmd == "reset") {
        std::vector<std::string> w;
        for (size_t q = 0; q < arg.size();) {
            size_t e = arg.find(' ', q);
            if (e == std::string::npos) e = arg.size();
            if (e > q) w.push_back(arg.substr(q, e - q));
            q = e + 1;
        }
        int p = w.empty() ? -1 : atoi(w[0].c_str()) - 1;
        int b = -1;
        for (int i = 0; i < CB_COUNT && w.size() > 1; i++)
            if (w[1] == ctl_button_key(i)) b = i;
        if (p < 0 || p >= CTL_PLAYERS) { fprintf(stderr, "[launcher] test: %s %s: no such player\n", cmd.c_str(), arg.c_str()); return; }
        if (cmd == "bind" && b >= 0 && w.size() >= 4) {
            bool pad = w[2].compare(0, 3, "pad") == 0;
            int slot = w[2].back() == '2';
            std::string in = arg.substr(arg.find(w[3], arg.find(w[2]) + w[2].size()));
            int k[CTL_SLOTS];
            PadIn pd[CTL_SLOTS];
            if (in == "none") cell_clear(p, b, slot, pad);
            else if (!controls_parse(in, k, pd) || (pad ? !pd[0].kind : !k[0])) fprintf(stderr, "[launcher] test: bind %s refused\n", arg.c_str());
            else S.ctl_note = pad ? controls_bind_pad(p, b, slot, pd[0]) : controls_bind_key(p, b, slot, k[0]);
        } else if (cmd == "capture" && b >= 0 && w.size() >= 3) capture_start(S, p, b, 0, w[2] == "pad");
        else if (cmd == "keys" && w.size() >= 2) S.ctl_note = controls_keyboard_preset(p, w[1] == "arrows" ? KEYS_ARROWS : w[1] == "wasd" ? KEYS_WASD : KEYS_NONE);
        else if (cmd == "controller" && w.size() >= 2) { g_controls[p].device = w[1]; controls_reassign(); }
        else if (cmd == "deadzone" && w.size() >= 2) g_controls[p].deadzone = atoi(w[1].c_str());
        else if (cmd == "reset") controls_defaults(p);
        else fprintf(stderr, "[launcher] test: %s %s?\n", cmd.c_str(), arg.c_str());
    } else if (cmd == "vpad") {   /* a virtual controller plugged in (SDL's), for `vpress` / `vaxis` */
        SDL_VirtualJoystickDesc d;
        SDL_zero(d);
        d.version = SDL_VIRTUAL_JOYSTICK_DESC_VERSION;
        d.type = SDL_JOYSTICK_TYPE_GAMECONTROLLER;
        d.naxes = SDL_CONTROLLER_AXIS_MAX;
        d.nbuttons = SDL_CONTROLLER_BUTTON_MAX;
        d.name = "Test controller";
        if (SDL_JoystickAttachVirtualEx(&d) < 0) fprintf(stderr, "[launcher] test: no virtual controller: %s\n", SDL_GetError());
    } else if (cmd == "vpress" || cmd == "vaxis") {   /* vpress BUTTON 0|1, vaxis AXIS VALUE: the last virtual one */
        SDL_Joystick *j = nullptr;
        for (int i = 0; i < SDL_NumJoysticks(); i++)
            if (SDL_JoystickIsVirtual(i)) j = SDL_JoystickFromInstanceID(SDL_JoystickGetDeviceInstanceID(i));
        if (!j) { fprintf(stderr, "[launcher] test: %s: no virtual controller open\n", cmd.c_str()); return; }
        if (cmd == "vpress") SDL_JoystickSetVirtualButton(j, SDL_GameControllerGetButtonFromString(a1.c_str()), (Uint8)atoi(a2.c_str()));
        else SDL_JoystickSetVirtualAxis(j, SDL_GameControllerGetAxisFromString(a1.c_str()), (Sint16)atoi(a2.c_str()));
    } else if (cmd == "set") {
        bool known = false;
        for (int i = 0; i < options_count(); i++)
            if (a1 == options_name(i)) {
                known = true;
                if (!options_set(i, a2)) fprintf(stderr, "[launcher] test: %s=%s refused\n", a1.c_str(), a2.c_str());
            }
        if (!known) fprintf(stderr, "[launcher] test: no option %s\n", a1.c_str());
    } else if (cmd == "rom") { snprintf(S.rom, sizeof S.rom, "%s", arg.c_str()); check_rom(S); }
    else if (cmd == "show") S.show = a1 != "0";
    else if (cmd == "focus") S.focus = a1;
    else if (cmd == "shot") *shot = arg;
    else if (cmd == "press") S.press = a1 == "play" ? PRESS_PLAY : PRESS_QUIT;
    else fprintf(stderr, "[launcher] test: unknown command %s\n", line.c_str());
}

