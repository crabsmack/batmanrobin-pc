/* launcher.cpp - the start window: the ROM, the options and the controls without the command line (the
 * kit's playbook/porting.md, "The player's front door"). Shown on a played start with no ROM, no input
 * script and no --benchmark on the command line (a double-click), unless settings.ini's [launcher]
 * show = 0 or the kit's harness environment (GENESIS_NO_LAUNCHER=1); --launcher shows it anyway,
 * --no-launcher skips it once. Dear ImGui (platform/native/external/imgui, MIT) on its own SDL window
 * and renderer, closed before the game's opens.
 *
 * It changes nothing the command line can't: the options go to settings.ini's [options] (options.cpp),
 * the controls to [player1] and [player2] (controls.cpp), the ROM to [rom], and the game is then handed
 * the ROM as a command line would, so it never knows a launcher ran. Every option of options.cpp's table
 * appears by itself: under "Other" with the table's own description until shown_table() gives it a
 * label, a group and help.
 *
 * Testing (no person): BR_LAUNCHER_TEST=FILE runs one command per frame on a hidden window (with
 * SDL_VIDEODRIVER=dummy, headless): `tab play|options|controls`, `set KEY VALUE` (an option), `rom PATH`,
 * `show 0|1`, `focus KEY`, `shot FILE.bmp`, `press play|quit`; for the Controls page `player N`, `bind P
 * BUTTON key|key2|pad|pad2 INPUT|none`, `capture P BUTTON key|pad`, `keys P arrows|wasd|none`,
 * `controller P auto|none|GUID`, `deadzone P N`, `reset P`, and a virtual controller: `vpad`, `vpress
 * BUTTON 0|1`, `vaxis AXIS VALUE` (SDL's names). runner.cpp's BR_LAUNCHER_DRYRUN=1 prints the plan
 * instead of starting the game.
 *
 * Adapted from the X-Men 2 port's platform/native/launcher.cpp (the same kit; its online play left out:
 * this port has no netplay).
 */
